def detail(text: str) -> None:
    print(f"  {text}", flush=True)


def shown(path: Path) -> str:
    try:
        return path.relative_to(df.ROOT).as_posix()
    except ValueError:
        return str(path)


def read_info(folder: Path) -> dict:
    try:
        return json.loads((folder / df.SHOWCASE_INFO).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def own_preview(folder: Path, info: dict) -> Path | None:
    """A preview image someone put into the showcase copy themselves: one that is not the screenshot
    this tool recorded in showcase.json. It is kept instead of a new screenshot."""
    for name in ("preview.png", "preview.jpg", "preview.jpeg", "preview.webp"):
        path = folder / name
        if path.is_file() and sha256(path) != info.get("generated"):
            return path
    return None


def take_preview(deck: Path, slide: str, step: str) -> Path:
    """A screenshot of one slide next to the deck: preview.png, or preview.jpg if the PNG is large."""
    url = deck.resolve().as_uri() + f"?preview={urllib.parse.quote(slide)}" + (f"&step={step}" if step else "")
    png = deck.with_name("preview.png")
    _browser.screenshot(url, png, PREVIEW_SIZE)
    if png.stat().st_size <= MAX_PNG:
        return png
    jpg = deck.with_name("preview.jpg")
    _browser.screenshot(url, jpg, PREVIEW_SIZE)
    png.unlink()
    return jpg


def publish(target: Path, into: Path, preview: str | None, force: bool, replace: bool) -> bool:
    """Copy one presentation into `into` (checked, with preview and showcase.json); False on errors."""
    folder = (target if target.is_dir() else target.parent).resolve()
    decks = df.find_decks(folder) if folder.is_dir() else []
    if len(decks) != 1:
        print(f"error: expected exactly one *_presentation.html in {folder}, found {len(decks)}", file=sys.stderr)
        return False
    deck, dest = decks[0], into / folder.name
    if dest.exists() and dest != folder and not replace:
        # A published copy may differ from the project on purpose (e.g. only material that may be published).
        print(f"error: {shown(dest)}/ exists and is maintained there: refresh it with "
              f"python tools/showcase.py \"{shown(dest)}\", or replace it from {folder.name} with --replace", file=sys.stderr)
        return False
    print(f"{folder.name} → {shown(dest)}/", flush=True)
    files, left_out = pack.needed_files(deck, check.deck_assets(deck))
    with tempfile.TemporaryDirectory(prefix="deck-showcase-") as tmp:
        staged = Path(tmp) / folder.name
        for rel in files:
            (staged / rel).parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(folder / rel, staged / rel)
        size = sum((staged / rel).stat().st_size for rel in files)
        detail(f"{len(files)} files used ({size / 1024:.0f} KB), {len(left_out)} left out")
        report = check.check_deck(staged / deck.name, progress=detail)
        for line in check.report_lines(report)[1:]:
            detail(line)
        if report.ok:
            detail("no problems found")
        elif not force:
            print("Not published: fix the problems above (or use --force).", file=sys.stderr)
            return False

        found = _browser.probe_file(staged / deck.name, INFO_PROBE)
        ids = found.pop("ids")
        old = read_info(dest)
        spec = preview or old.get("preview") or "0"
        slide, _, step = spec.partition(":")
        if not (slide in ids or (slide.isdigit() and int(slide) < len(ids))) or not (step == "" or step.isdigit()):
            print(f"error: preview {spec!r}: no such slide (use a slide id or 0-based index, optionally :step; "
                  f"ids: {', '.join(ids)})", file=sys.stderr)
            return False
        custom = None if preview else own_preview(dest, old)
        if custom:
            image, generated = staged / custom.name, None
            shutil.copy2(custom, image)
            detail(f"preview: your own {image.name} is kept (--preview replaces it with a screenshot)")
        else:
            image = take_preview(staged / deck.name, slide, step)
            generated = sha256(image)
            detail(f"preview: slide {spec} → {image.name} ({image.stat().st_size / 1024:.0f} KB)")
        info = {"deck": deck.name, **found, "slides": len(ids), "preview": spec, "image": image.name,
                "generated": generated}
        (staged / df.SHOWCASE_INFO).write_text(json.dumps(info, indent=2, ensure_ascii=False) + "\n",
                                               encoding="utf-8", newline="\n")
        if dest.exists():
            shutil.rmtree(dest)
        shutil.copytree(staged, dest)
    detail("published" + ("" if report.ok else f" with {len(report.issues)} problem(s) (--force)"))
    return True


def repo_url() -> str | None:
    """This repository's GitHub page (from the origin remote), for the link at the bottom of the index."""
    try:
        url = subprocess.run(["git", "-C", str(df.ROOT), "remote", "get-url", "origin"], capture_output=True,
                             text=True, timeout=30).stdout.strip()
    except (OSError, subprocess.TimeoutExpired):
        return None
    m = re.match(r"^(?:https://(?:[^@/]+@)?github\.com/|git@github\.com:)([\w.-]+/[\w.-]+?)(?:\.git)?/?$", url)
    return f"https://github.com/{m.group(1)}" if m else None


def card(name: str, info: dict) -> str:
    esc = html.escape
    href = esc(urllib.parse.quote(f"{name}/{info['deck']}"))
    img = esc(urllib.parse.quote(f"{name}/{info['image']}"))
    course = info.get("course") or {}
    who = " · ".join(p for p in (info.get("presenter"), course.get("title"),
                                 " ".join(filter(None, (course.get("type"), course.get("semester"))))) if p)
    facts = f"{info['slides']} slides" + (f", {info['interactive']} of them interactive" if info.get("interactive") else "")
    lines = [
        '    <article class="talk">',
        f'      <a href="{href}" tabindex="-1" aria-hidden="true"><img src="{img}" width="{PREVIEW_SIZE[0]}"'
        f' height="{PREVIEW_SIZE[1]}" alt="" loading="lazy"></a>',
        '      <div class="body">',
        f'        <h2><a href="{href}">{esc(info.get("title") or name)}</a></h2>',
        *([f'        <p class="meta">{esc(info["subtitle"])}</p>'] if info.get("subtitle") else []),
        *([f'        <p class="meta">{esc(who)}</p>'] if who else []),
        f'        <p class="facts">{esc(facts)}</p>',
        f'        <a class="open" href="{href}">Present ▸</a>',
        '      </div>',
        '    </article>',
    ]
    return "\n".join(lines)


def write_index(into: Path) -> int:
    """Rewrite index.html from the showcase.json of every talk in `into`; returns the number of talks."""
    talks = [(p.parent.name, read_info(p.parent)) for p in sorted(into.glob(f"*/{df.SHOWCASE_INFO}"),
                                                                  key=lambda p: p.parent.name.lower())]
    cards = [card(name, info) for name, info in talks if info.get("deck") and (into / name / info["deck"]).is_file()]
    repo = repo_url()
    footer = (f'Made with <a href="{html.escape(repo)}">CapySlides</a>: the engine, the tools and these talks are on GitHub.'
              if repo else "Made with CapySlides.")
    page = PAGE.replace("@@CARDS@@", "\n".join(cards) or '    <p class="meta">No talks yet.</p>').replace("@@FOOTER@@", footer)
    (into / "index.html").write_text(page, encoding="utf-8", newline="\n")
    return len(cards)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("folders", nargs="*", type=Path, help="presentation folders to publish (none: only rewrite index.html)")
    ap.add_argument("--preview", metavar="SLIDE[:STEP]", help="slide of the preview image: id or 0-based index, optionally :step")
    ap.add_argument("--force", action="store_true", help="publish even if the check finds problems")
    ap.add_argument("--replace", action="store_true", help="replace an existing showcase copy from another folder")
    ap.add_argument("--into", type=Path, default=df.SHOWCASE, help=f"the showcase folder (default: {df.SHOWCASE})")
    args = ap.parse_args(argv)
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
        sys.stderr.reconfigure(encoding="utf-8")
    if args.preview and len(args.folders) != 1:
        print("error: --preview needs exactly one folder", file=sys.stderr)
        return 2
    if args.folders and not _browser.find_browser():
        print("error: showcase.py needs Chrome/Edge (to check the copy and take the preview)", file=sys.stderr)
        return 2
    missing = [f for f in args.folders if not f.exists()]
    if missing:
        print(f"error: {missing[0]} does not exist", file=sys.stderr)
        return 2

    into = args.into.resolve()
    into.mkdir(parents=True, exist_ok=True)
    results = [publish(folder, into, args.preview, args.force, args.replace) for folder in args.folders]
    n = write_index(into)
    print(f"Wrote {shown(into / 'index.html')} ({n} talk{'s' if n != 1 else ''})")
    return 0 if all(results) else 1


if __name__ == "__main__":
    sys.exit(main())
